"""项目路径解析 / Project path resolution.

唯一允许把「项目在哪」写死的地方 —— 其余模块一律通过本模块取路径，
避免绝对路径散落各处（换机器 / 换目录时只需改环境变量）。

The single place allowed to know "where the project lives"; every other module
resolves paths through here. Override with the ``VIDEOGEN_PROJECT_ROOT``
environment variable instead of editing code.
"""

from __future__ import annotations

import os
from pathlib import Path

# src/videogen/paths.py → parents[2] == 项目根（含 docs/ assets/ src/）
_DEFAULT_ROOT = Path(__file__).resolve().parents[2]


def _resolve_project_root() -> Path:
    """优先环境变量，其次按包位置推导。

    Prefer the env var, else derive from this package's location.
    """
    override = os.environ.get("VIDEOGEN_PROJECT_ROOT")
    if override:
        return Path(override).expanduser().resolve()
    return _DEFAULT_ROOT


PROJECT_ROOT: Path = _resolve_project_root()
"""项目根目录 / Project root directory."""


def docs_dir() -> Path:
    """文档目录 / Documentation directory."""
    return PROJECT_ROOT / "docs"


def assets_dir() -> Path:
    """素材目录（图片 / 音频 / 字体 / 目录索引）/ Asset directory."""
    return PROJECT_ROOT / "assets"


def asset_sets_dir() -> Path:
    """多素材集根目录 / Root of the per-article asset sets.

    每篇文章一套素材，放在 ``assets/sets/<name>/``：
    这样同一个工程能处理任意文章，而不是把素材名写死在代码里。

    One folder per article under ``assets/sets/<name>/`` so a single project can
    handle arbitrary articles instead of hard-coding asset filenames.
    """
    override = os.environ.get("VIDEOGEN_ASSET_SETS")
    if override:
        return Path(override).expanduser().resolve()
    return assets_dir() / "sets"


def out_dir() -> Path:
    """渲染产物目录 / Rendered-artifact directory."""
    return PROJECT_ROOT / "out"


# ── 交付物目录结构 / Deliverable layout ────────────────────────────────────
# 一套交付物 = ``out/<素材集>/<kind>/``，内部**按文件类型**分目录：
#
#     out/<set>/<short|mid>/
#     ├── video/         成片 mp4（按方向命名）
#     ├── shots/         分镜片段（内含 <aspect>/ 与 manifest.json）
#     ├── subtitles/     字幕 srt
#     ├── storyboard/    spec.json + props + 可读镜头表 —— 二次修改的输入
#     ├── qa/            抽帧品检图
#     └── logs/          渲染日志
#
# 为什么要固定这套结构：早先同一套产物散在三处（成片在 out/<set>/<kind>/、
# 抽帧在 out/<set>/qa/ 与 out/qa_opt/、中间 props 在 out/runs/），
# 找一个文件要翻四个顶层目录。现在「找出片 / 找字幕 / 找片段 / 找分镜数据」
# 各自有唯一位置。
#
# One bundle per (asset set, kind), with a subdirectory per file type, so every
# artefact has exactly one home.


def deliverable_dir(set_name: str, kind: str) -> Path:
    """一套交付物的根 / Root of one deliverable bundle."""
    return out_dir() / set_name / kind


def video_dir(set_name: str, kind: str) -> Path:
    """成片目录 / Finished films."""
    return deliverable_dir(set_name, kind) / "video"


def shots_dir(set_name: str, kind: str) -> Path:
    """分镜片段目录（内含 <方向>/ 子目录）/ Per-shot clips (per orientation)."""
    return deliverable_dir(set_name, kind) / "shots"


def subtitles_dir(set_name: str, kind: str) -> Path:
    """字幕目录 / Subtitle files."""
    return deliverable_dir(set_name, kind) / "subtitles"


def storyboard_dir(set_name: str, kind: str) -> Path:
    """分镜数据目录（spec / props / 镜头表）/ Storyboard data."""
    return deliverable_dir(set_name, kind) / "storyboard"


def qa_dir(set_name: str, kind: str) -> Path:
    """抽帧品检目录 / QA stills."""
    return deliverable_dir(set_name, kind) / "qa"


def logs_dir(set_name: str, kind: str) -> Path:
    """渲染日志目录 / Render logs."""
    return deliverable_dir(set_name, kind) / "logs"


def ensure_deliverable_dirs(set_name: str, kind: str) -> Path:
    """建好一套交付物的全部子目录 / Create every subdirectory of a bundle.

    :returns: 交付物根目录 / the bundle root.
    """
    for path in (
        video_dir(set_name, kind),
        shots_dir(set_name, kind),
        subtitles_dir(set_name, kind),
        storyboard_dir(set_name, kind),
        qa_dir(set_name, kind),
        logs_dir(set_name, kind),
    ):
        path.mkdir(parents=True, exist_ok=True)
    return deliverable_dir(set_name, kind)


def shot_catalog_json() -> Path:
    """镜头卡索引 JSON（由 ``scripts/build_shot_catalog.py`` 生成）。

    Shot-card catalog JSON, generated by ``scripts/build_shot_catalog.py``.
    """
    return assets_dir() / "shot_catalog.json"


def images_index_json() -> Path:
    """图片素材语义索引 JSON / Image asset semantic index JSON."""
    return assets_dir() / "images" / "index.json"


def source_repo_root() -> Path:
    """video-shotcraft 源仓库根（与本项目同级）。

    Root of the ``video-shotcraft`` source repo (a sibling of this project).

    注意：本工程 **不 import** 该仓库的代码，只读取其镜头卡文档与资产；
    组件一律 copy 进 Remotion 工程后再改（见 SKILL.md「资产使用方式」）。
    """
    override = os.environ.get("VIDEOGEN_SHOTCRAFT_ROOT")
    if override:
        return Path(override).expanduser().resolve()
    return PROJECT_ROOT.parent / "video-shotcraft"
